-- =============================================================================
--  HelpDesk 2.0 — Schema do banco NOVO (PostgreSQL 16)
--
--  Todos os horários são gravados em UTC (timestamptz).
--  Colunas legacy_id guardam a chave do registro de origem no sistema legado,
--  para rastreabilidade e para permitir reexecutar a migração (idempotência).
-- =============================================================================

CREATE TYPE user_role          AS ENUM ('requester', 'agent', 'admin');
CREATE TYPE user_status        AS ENUM ('active', 'inactive');
CREATE TYPE ticket_status      AS ENUM ('open', 'in_progress', 'waiting_customer', 'resolved', 'closed', 'canceled');
CREATE TYPE ticket_priority    AS ENUM ('low', 'medium', 'high', 'critical');
CREATE TYPE comment_visibility AS ENUM ('public', 'internal');
CREATE TYPE issue_severity     AS ENUM ('info', 'warning', 'error');

-- -----------------------------------------------------------------------------
-- Departamentos
-- -----------------------------------------------------------------------------
CREATE TABLE departments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(80)  NOT NULL,
    is_active   boolean      NOT NULL DEFAULT true,
    legacy_id   integer      UNIQUE,
    created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX departments_name_uq ON departments (lower(name));

-- -----------------------------------------------------------------------------
-- Usuários
-- -----------------------------------------------------------------------------
CREATE TABLE users (
    id                   uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    first_name           varchar(60)   NOT NULL,
    last_name            varchar(120),
    email                varchar(254)  NOT NULL UNIQUE,
    phone                varchar(16),
    department_id        bigint        REFERENCES departments (id),
    role                 user_role     NOT NULL DEFAULT 'requester',
    status               user_status   NOT NULL DEFAULT 'active',
    password_hash        text,                       -- bcrypt/argon2; NULL = precisa definir senha
    must_reset_password  boolean       NOT NULL DEFAULT true,
    created_at           timestamptz   NOT NULL,
    updated_at           timestamptz   NOT NULL DEFAULT now(),
    legacy_id            integer       UNIQUE,

    CONSTRAINT users_email_lower_ck CHECK (email = lower(btrim(email))),
    CONSTRAINT users_phone_e164_ck  CHECK (phone ~ '^\+55[1-9][1-9][0-9]{8,9}$'),
    CONSTRAINT users_first_name_ck  CHECK (btrim(first_name) <> '')
);

-- -----------------------------------------------------------------------------
-- Categorias (hierarquia de 1 ou mais níveis; SLA sempre explícito, sem herança)
-- -----------------------------------------------------------------------------
CREATE TABLE categories (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    varchar(80)  NOT NULL,
    parent_id               bigint       REFERENCES categories (id),
    resolution_sla_minutes  integer      NOT NULL CHECK (resolution_sla_minutes > 0),
    is_active               boolean      NOT NULL DEFAULT true,
    legacy_id               integer      UNIQUE,

    CONSTRAINT categories_not_self_parent_ck CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE UNIQUE INDEX categories_parent_name_uq
    ON categories (COALESCE(parent_id, 0), lower(name));

-- -----------------------------------------------------------------------------
-- Chamados
-- -----------------------------------------------------------------------------
CREATE TABLE tickets (
    id                    uuid             PRIMARY KEY DEFAULT gen_random_uuid(),
    code                  varchar(20)      NOT NULL UNIQUE,     -- ex.: HD-2024-001030
    title                 varchar(120)     NOT NULL,
    description           text             NOT NULL,
    requester_id          uuid             NOT NULL REFERENCES users (id),
    assignee_id           uuid             REFERENCES users (id),
    category_id           bigint           NOT NULL REFERENCES categories (id),
    priority              ticket_priority  NOT NULL DEFAULT 'medium',
    status                ticket_status    NOT NULL DEFAULT 'open',
    opened_at             timestamptz      NOT NULL,
    first_response_at     timestamptz,
    resolved_at           timestamptz,
    closed_at             timestamptz,
    due_at                timestamptz      NOT NULL,
    sla_breached          boolean,
    satisfaction_score    smallint         CHECK (satisfaction_score BETWEEN 1 AND 5),
    satisfaction_comment  text,
    created_at            timestamptz      NOT NULL DEFAULT now(),
    updated_at            timestamptz      NOT NULL DEFAULT now(),
    legacy_id             integer          UNIQUE,

    CONSTRAINT tickets_code_ck CHECK (code ~ '^HD-[0-9]{4}-[0-9]{6}$'),
    CONSTRAINT tickets_title_ck CHECK (btrim(title) <> ''),
    CONSTRAINT tickets_description_ck CHECK (btrim(description) <> ''),
    CONSTRAINT tickets_dates_ck CHECK (
            (first_response_at IS NULL OR first_response_at >= opened_at)
        AND (resolved_at       IS NULL OR resolved_at       >= opened_at)
        AND (closed_at         IS NULL OR closed_at         >= opened_at)
        AND (resolved_at IS NULL OR closed_at IS NULL OR resolved_at <= closed_at)
        AND due_at > opened_at
    ),
    -- coerência entre status e datas
    CONSTRAINT tickets_status_dates_ck CHECK (
        CASE status
            WHEN 'open'             THEN resolved_at IS NULL AND closed_at IS NULL
            WHEN 'in_progress'      THEN resolved_at IS NULL AND closed_at IS NULL
            WHEN 'waiting_customer' THEN resolved_at IS NULL AND closed_at IS NULL
            WHEN 'resolved'         THEN resolved_at IS NOT NULL AND closed_at IS NULL
            WHEN 'closed'           THEN resolved_at IS NOT NULL AND closed_at IS NOT NULL
            WHEN 'canceled'         THEN resolved_at IS NULL AND closed_at IS NOT NULL
        END
    ),
    CONSTRAINT tickets_in_progress_assignee_ck CHECK (
        status NOT IN ('in_progress', 'waiting_customer') OR assignee_id IS NOT NULL
    ),
    CONSTRAINT tickets_satisfaction_ck CHECK (
        (satisfaction_score IS NULL AND satisfaction_comment IS NULL)
        OR status IN ('resolved', 'closed')
    ),
    CONSTRAINT tickets_satisfaction_comment_ck CHECK (
        satisfaction_comment IS NULL OR satisfaction_score IS NOT NULL
    ),
    CONSTRAINT tickets_sla_breached_ck CHECK (
        (status = 'canceled') = (sla_breached IS NULL)
    )
);
CREATE INDEX tickets_requester_idx ON tickets (requester_id);
CREATE INDEX tickets_assignee_idx  ON tickets (assignee_id);
CREATE INDEX tickets_status_idx    ON tickets (status);

-- -----------------------------------------------------------------------------
-- Comentários (somente mensagens escritas por pessoas; mudanças de status NÃO)
-- -----------------------------------------------------------------------------
CREATE TABLE ticket_comments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   uuid                NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    author_id   uuid                NOT NULL REFERENCES users (id),
    body        text                NOT NULL CHECK (btrim(body) <> ''),
    visibility  comment_visibility  NOT NULL DEFAULT 'public',
    created_at  timestamptz         NOT NULL,
    legacy_id   integer             UNIQUE
);
CREATE INDEX ticket_comments_ticket_idx ON ticket_comments (ticket_id, created_at);

-- -----------------------------------------------------------------------------
-- Histórico de status
-- -----------------------------------------------------------------------------
CREATE TABLE ticket_status_history (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id              uuid           NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    from_status            ticket_status,                 -- NULL = criação do chamado
    to_status              ticket_status  NOT NULL,
    changed_by             uuid           REFERENCES users (id),  -- NULL = sistema
    changed_at             timestamptz    NOT NULL,
    legacy_interaction_id  integer        UNIQUE
);
CREATE INDEX ticket_status_history_ticket_idx ON ticket_status_history (ticket_id, changed_at);

-- -----------------------------------------------------------------------------
-- Tags
-- -----------------------------------------------------------------------------
CREATE TABLE tags (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  varchar(40) NOT NULL UNIQUE,
    CONSTRAINT tags_slug_ck CHECK (name ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

CREATE TABLE ticket_tags (
    ticket_id  uuid    NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    tag_id     bigint  NOT NULL REFERENCES tags (id),
    PRIMARY KEY (ticket_id, tag_id)
);

-- -----------------------------------------------------------------------------
-- Anexos (os binários vão para um object storage; aqui fica só a referência)
-- -----------------------------------------------------------------------------
CREATE TABLE attachments (
    id           uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_id    uuid          NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    file_name    varchar(255)  NOT NULL,     -- nome original, exibido ao usuário
    storage_key  varchar(500)  NOT NULL UNIQUE,
    mime_type    varchar(100)  NOT NULL,
    size_bytes   bigint        NOT NULL CHECK (size_bytes > 0),
    uploaded_at  timestamptz   NOT NULL,
    legacy_id    integer       UNIQUE,

    CONSTRAINT attachments_storage_key_ck CHECK (storage_key ~ '^tickets/HD-[0-9]{4}-[0-9]{6}/[a-z0-9._-]+$')
);

-- -----------------------------------------------------------------------------
-- Tabelas de apoio à migração
-- -----------------------------------------------------------------------------

-- De/para de TODOS os ids do legado (inclusive registros unificados/duplicados).
CREATE TABLE migration_id_map (
    entity     varchar(30)  NOT NULL,   -- department | category | user | ticket
    legacy_id  integer      NOT NULL,
    new_id     text         NOT NULL,   -- id (bigint ou uuid) do registro no banco novo
    PRIMARY KEY (entity, legacy_id)
);

-- Tudo que foi corrigido, unificado, descartado ou não pôde ser migrado.
CREATE TABLE migration_issues (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity      varchar(30)     NOT NULL,   -- department | category | user | ticket | interaction | attachment
    legacy_id   integer,
    severity    issue_severity  NOT NULL,
    code        varchar(60)     NOT NULL,   -- ex.: USER_MERGED, INVALID_EMAIL
    message     text            NOT NULL,
    created_at  timestamptz     NOT NULL DEFAULT now()
);
